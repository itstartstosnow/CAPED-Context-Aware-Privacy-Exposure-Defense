"""Screen context classification based on Android Activity/package name.

两步分类管线
============

步骤 1 — App 基础 ScreenContext（数据驱动）
  输入：package_name（不含 Activity 部分）
  查找顺序：
    1a. app_context_db.json 精确包名或前缀匹配
    1b. 包名关键词启发式（优先级从高到低）：
          .settings/.setting 后缀 → settings（排除 exclusion 名单）
          含 launcher/homescreen → launcher
          含 camera → camera
          含 gallery/photos/photo → gallery
          含 contacts/people → contacts
          含 browser → public_content
    1c. → unknown

步骤 2 — Activity 页面调整（数据驱动，来自 subpage_rules.py Table B1）
  输入：步骤 1 结果 + activity_class 字符串
  查找顺序：
    subpage_rules.CLASSIFICATION_RULES — 优先级排列的 glob 规则
    （Layer 1: 已知 app 精确打表; Layer 2: messaging 通配; Layer 3: 全局 settings）

枚举类别
--------
gallery           — 相册/图片选择器（用户主动进入）
map_view          — 地图/导航（地理位置暴露）
messaging         — 即时通讯（联系人头像、共享照片）
content_feed      — social media feeds, shopping/recommendation feeds, video streaming
settings          — 系统/应用设置界面
public_content    — 公开信息（浏览器、YouTube 非个人内容）
financial         — 支付/金融类（账号、金额、付款码，最高风险）
personal_profile  — "我的"页面（真实姓名、手机号、头像、绑定支付方式）
camera            — 相机实时预览（区别于相册：实时捕获 vs 已存储）
contacts          — 联系人列表（社交关系图暴露）
launcher          — Android 主屏/桌面（显示已安装 App 列表）
tool              — 工具类 App（时钟、录音、绘图、音乐播放器等），无个人隐私内容
game              — 游戏 App，无个人隐私内容
health            — 健康/运动类 App，含高度敏感个人健康数据
file              — 文件管理器 / 存储浏览器
unknown           — 无法匹配时的保守默认值
"""

import json
import logging
import pathlib
from enum import Enum

logger = logging.getLogger(__name__)


class ScreenContext(Enum):
    gallery = "gallery"
    map_view = "map_view"
    messaging = "messaging"               # fallback for unknown messaging apps
    messaging_list = "messaging_list"     # chat/DM list screen (multiple contacts visible)
    messaging_conversation = "messaging_conversation"  # inside a single conversation
    content_feed = "content_feed"   # social media, shopping & recommendation feeds, video streaming
    settings = "settings"
    public_content = "public_content"
    financial = "financial"
    personal_profile = "personal_profile"
    camera = "camera"
    contacts = "contacts"
    launcher = "launcher"
    tool = "tool"                         # utility apps: clock, recorder, draw, music player, etc.
    game = "game"                         # games: card, casual, puzzle, adventure, etc.
    health = "health"                     # health/fitness: menstrual, medical, workout, etc.
    file = "file"                         # file manager / storage browser (Files app, ES Explorer, etc.)
    unknown = "unknown"


# ---------------------------------------------------------------------------
# Lazy import for subpage rules (Table B) — avoids circular imports.
# ---------------------------------------------------------------------------
def _get_classify_subpage():
    from android_world.agents.privacy.subpage_rules import classify_subpage  # pylint: disable=import-outside-toplevel
    return classify_subpage

# ---------------------------------------------------------------------------
# App context database — loaded lazily from app_context_db.json.
# The JSON file is generated by test/build_app_context_db.py and contains
# exact package name → ScreenContext value mappings.  It is the authoritative
# source for Step 1 of the two-step classification pipeline.
# ---------------------------------------------------------------------------
_APP_DB: dict | None = None


def _load_app_db() -> dict:
    global _APP_DB
    if _APP_DB is None:
        db_path = pathlib.Path(__file__).parent / "app_context_db.json"
        try:
            with open(db_path, encoding="utf-8") as f:
                _APP_DB = json.load(f)
        except FileNotFoundError:
            logger.warning("[screen_ctx] app_context_db.json not found at %s; DB lookup disabled", db_path)
            _APP_DB = {}
    return _APP_DB


def _get_app_base_context(pkg: str) -> ScreenContext:
    """Step 1: Determine app-level base ScreenContext.

    Lookup order:
      1a. Exact match in app_context_db.json
      1b. Prefix match in app_context_db.json (e.g. com.tencent.mm.plugin → messaging)
      1c. Package name keyword heuristics (highest-priority keywords first):
            .settings/.setting suffix → settings (excluding known non-system apps)
            contains launcher/homescreen → launcher
            contains camera → camera
            contains gallery/photos/photo → gallery
            contains contacts/people → contacts
            contains browser → public_content
      → unknown
    """
    db = _load_app_db()

    # 1a. Exact package match
    if pkg in db and not pkg.startswith("__"):
        ctx_val = db[pkg]["context"]
        logger.info("[screen_ctx] db_exact: pkg=%s → %s", pkg, ctx_val)
        return ScreenContext(ctx_val)

    # 1b. Prefix match (handles sub-packages like com.tencent.mm.plugin.*)
    for key, entry in db.items():
        if key.startswith("__"):
            continue
        if pkg.startswith(key + "."):
            ctx_val = entry["context"]
            logger.info("[screen_ctx] db_prefix: pkg=%s prefix=%s → %s", pkg, key, ctx_val)
            return ScreenContext(ctx_val)

    # 1c. Package name keyword heuristics
    pkg_lower = pkg.lower()

    # settings suffix — check first (highest priority) to avoid false matches
    if pkg_lower.endswith(".settings") or pkg_lower.endswith(".setting"):
        logger.info("[screen_ctx] heuristic: settings_suffix pkg=%s → settings", pkg)
        return ScreenContext.settings

    if any(kw in pkg_lower for kw in ("launcher", "homescreen")):
        logger.info("[screen_ctx] heuristic: launcher kw in pkg=%s → launcher", pkg)
        return ScreenContext.launcher

    if "camera" in pkg_lower:
        logger.info("[screen_ctx] heuristic: camera kw in pkg=%s → camera", pkg)
        return ScreenContext.camera

    if any(kw in pkg_lower for kw in ("gallery", "photos", "photo")):
        logger.info("[screen_ctx] heuristic: gallery kw in pkg=%s → gallery", pkg)
        return ScreenContext.gallery

    if any(kw in pkg_lower for kw in ("contacts", "people")):
        logger.info("[screen_ctx] heuristic: contacts kw in pkg=%s → contacts", pkg)
        return ScreenContext.contacts

    if "browser" in pkg_lower:
        logger.info("[screen_ctx] heuristic: browser kw in pkg=%s → public_content", pkg)
        return ScreenContext.public_content

    # messaging: sms / messenger patterns
    if any(kw in pkg_lower for kw in (
        "smsmessenger", "sms", "messenger",
        "mail", "email", "chat",
    )):
        logger.info("[screen_ctx] heuristic: messaging kw in pkg=%s → messaging", pkg)
        return ScreenContext.messaging

    # financial: banking / wallet / investment apps
    if any(kw in pkg_lower for kw in (
        "expense", "budget",
        "bank", "wallet", "finance", "invest", "loan",
        "creditcard", "brokerage", "fintech", "alipay",
    )):
        logger.info("[screen_ctx] heuristic: financial kw in pkg=%s → financial", pkg)
        return ScreenContext.financial

    # health: sensitive personal health / fitness data
    if any(kw in pkg_lower for kw in (
        "health", "medical", "medicine", "menstrual", "period", "pregnancy",
        "pregnant", "fitness", "workout", "gym", "clinic", "hospital",
        "doctor", "pharmacy", "drug", "sport", "exercise",
    )):
        logger.info("[screen_ctx] heuristic: health kw in pkg=%s → health", pkg)
        return ScreenContext.health

    # tool: utility apps with no personal content
    # Note: db lookup runs first, so known streaming/social apps already in the db
    # are not affected by broad keywords like "music".
    if any(kw in pkg_lower for kw in (
        "clock", "alarm", "recorder", "audiorecorder",
        "draw", "calculator", "flashlight", "weather",
        "compass", "barcode", "scanner", "notes", "notepad",
        "recipe", "cookbook",                          # recipe/cooking apps
        "vlc", "mediaplayer", "musicplayer", "music",  # local media players
        "inputmethod", "keyboard", "ime",              # input methods
        "office", "editor", "viewer", "pdf",           # office/document tools
    )):
        logger.info("[screen_ctx] heuristic: tool kw in pkg=%s → tool", pkg)
        return ScreenContext.tool

    # content_feed: shopping / marketplace apps
    if any(kw in pkg_lower for kw in ("shop", "store", "market")):
        logger.info("[screen_ctx] heuristic: content_feed kw in pkg=%s → content_feed", pkg)
        return ScreenContext.content_feed

    logger.info("[screen_ctx] no match: pkg=%s → unknown", pkg)
    return ScreenContext.unknown


def _classify_from_activity(activity_name: str) -> ScreenContext:
    """Classify screen from activity/package name only (no UI dump).

    Two-step pipeline:
      Step 1. _get_app_base_context() — DB lookup + package heuristics
      Step 2. Table B1 classify_subpage() — priority-ordered glob rules
    """
    if not activity_name:
        return ScreenContext.unknown

    parts = activity_name.split("/", 1)
    pkg = parts[0].strip()
    activity_class = parts[1].strip() if len(parts) > 1 else ""

    # Step 1: App-level base context (DB + package heuristics)
    base_ctx = _get_app_base_context(pkg)

    # Step 2: Table B1 subpage classification
    if activity_class:
        classify_subpage = _get_classify_subpage()
        refined = classify_subpage(pkg, base_ctx, activity_class)
        if refined is not None:
            return refined

    return base_ctx


def classify_screen(
    activity_name: str,
    ui_dump_xml: str = "",
) -> ScreenContext:
    """Classify the current screen context.

    Priority:
      0. (Optional) uiautomator XML page-type analysis via page_classifier —
         most accurate, uses actual UI widget patterns from real ADB data.
         Falls back to activity-based if page_classifier returns unknown.
      1–2. Two-step pipeline via _classify_from_activity():
           Step 2a. _ACTIVITY_RULES known Activity match (highest priority)
           Step 1.  app_context_db.json DB lookup + package heuristics
           Step 2. classify_subpage() — Table B1 priority-ordered glob rules

    Args:
        activity_name: Full Android activity string, e.g.
            "com.tencent.mm/.plugin.sns.ui.SnsTimeLineUI"
            or just a package name "com.tencent.mm".
        ui_dump_xml: Optional uiautomator XML string from
            ``adb shell uiautomator dump``.  When provided, page_classifier
            is consulted first for page-level accuracy.  Passing this is
            optional — omit it when the dump is unavailable or too slow to
            obtain (it adds ~5–30 s per ADB call).

    Returns:
        ScreenContext enum value.
    """
    # Priority 0: page_classifier (XML-based, most accurate)
    if ui_dump_xml:
        try:
            from android_world.agents.privacy import page_classifier as _pc  # lazy import
            page_type = _pc.classify_page_from_ui_dump(ui_dump_xml, activity_name)
            if page_type != _pc.PageType.unknown:
                app_ctx = _classify_from_activity(activity_name)
                return _pc.page_type_to_screen_context(page_type, app_ctx)
        except Exception as e:  # pylint: disable=broad-except
            logger.debug("[screen_ctx] page_classifier unavailable: %s", e)

    # Priorities 1-4: activity / package name rules
    return _classify_from_activity(activity_name)
